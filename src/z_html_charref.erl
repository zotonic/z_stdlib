-export([charref/1]).

%% External API.

%% @doc Convert a decimal charref, hex charref, or HTML entity to unicode
%%      codepoints, or return undefined on failure.
%%      The input should not include an ampersand or semicolon.
%%      charref("#38") = 38, charref("#x26") = 38, charref("amp") = 38.
-spec charref(binary() | string()) -> integer() | [integer()] | undefined.
charref(<<"#", C, B/binary>>) when C =:= $x orelse C =:= $X ->
    try erlang:binary_to_integer(B, 16)
    catch
        error:badarg -> undefined
    end;
charref(<<"#", B/binary>>) ->
    try binary_to_integer(B)
    catch
        error:badarg -> undefined
    end;
charref(B) when is_binary(B) ->
    entity_binary(B);
charref([$#, C | L]) when C =:= $x orelse C =:= $X ->
    try erlang:list_to_integer(L, 16)
    catch
        error:badarg -> undefined
    end;
charref([$# | L]) ->
    try list_to_integer(L)
    catch
        error:badarg -> undefined
    end;
charref(L) ->
    entity(L).

